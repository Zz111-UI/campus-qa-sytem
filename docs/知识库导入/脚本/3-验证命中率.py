    for q in queries:
        total += 1
        res = advisor.search_kb(q, top_k=3)
        top = res[0]["id"] if res else None
        ok1 = top == expect_id
        if ok1:
            hit_top1 += 1
        else:
            got = ", ".join(f'{r["id"]}({r["question"][:14]})' for r in res) or "无命中"
