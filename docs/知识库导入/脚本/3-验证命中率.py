def _find_root(start):
    """从脚本位置向上查找项目根目录（含 advisor.py）。"""
    for d in [start, *start.parents]:
        if (d / "advisor.py").exists():
            return d
    raise SystemExit("未找到项目根目录，请保持压缩包内的目录结构后再运行本脚本")


